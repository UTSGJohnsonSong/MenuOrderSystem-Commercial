/*
 * 菜品库：内置菜品的静态数据，所有空间共享同一份。数量看 LIBRARY_DISHES.length，
 * 不在注释里写数字——上一版写着「300 道」时实际已经 302 道了。
 * 用户在 /chufang/library 里搜索后挑选加入自己的菜单（写入 menu_items），
 * 加入后与手动添加的菜完全等价，可自由编辑/换图/归档。
 *
 * cat 是「建议分类」，对应 lib/categories.ts 的预置类目 id；
 * 用户加入时可以改成自己空间里的任意分类。
 * tags 只服务于搜索（别名/主料/做法），不展示给用户。
 *
 * img 指向 public/library/<img>.jpg：2026-07-30 导入的 177 张统一风格水彩插画，
 * 560x560 / JPEG q78 / 均 51KB。服务器只有 4 Mbps，不要再往上加尺寸。
 * 没有 img 的菜暂时无图，列表和详情都有渐变占位兜底；
 * 管理员在 /admin 配的图（library_images 表）优先级更高。
 */

export interface LibraryDish {
  name: string;
  cat: string;
  tags: string[];
  ingredients: string;
  instructions: string;
  /** Slug under public/library/, e.g. "lib-001". Absent = no illustration yet. */
  img?: string;
}

