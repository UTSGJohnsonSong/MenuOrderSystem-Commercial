/** Static illustration for a library dish, or null when it has none. */
export function libraryImageUrl(dish: LibraryDish): string | null {
  return dish.img ? '/library/' + dish.img + '.jpg' : null;
}

/**
 * 120x120 版本，给列表里的小缩略图用（public/library/thumb/）。
 *
 * 菜品库列表一屏能出十几行，每行的图只有 52x52，用 560 的原图渲染等于
 * 一个游客翻完 416 行要拉 8.7MB —— 服务器上行只有 4 Mbps，那是 20 秒独占。
 * 缩略图全套加起来 0.58MB，省 15 倍。
 * 加进用户自己菜单时仍然存原图 URL（详情页是整屏宽的），不要在那里用这个。
 */
export function libraryThumbUrl(dish: LibraryDish): string | null {
  return dish.img ? '/library/thumb/' + dish.img + '.jpg' : null;
}

